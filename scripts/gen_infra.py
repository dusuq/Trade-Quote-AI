#!/usr/bin/env python3
"""Generate per-unit deployment artifacts from infra/services.yml (T309 / M24).

Writes, for every unit in the registry:
    <path>/Dockerfile      — multi-stage, non-root production image
    <path>/.dockerignore   — keeps build context small and secrets out
    <path>/fly.toml        — Fly.io app config (health checks, scaling, ports)

Plus, once per run:
    infra/monitoring/prometheus/targets/services-local.json     — blackbox /health file_sd targets
    infra/monitoring/prometheus/targets/services-fly.json       — blackbox /health file_sd targets
    infra/monitoring/prometheus/targets/app-metrics-local.json  — direct /metrics file_sd targets (T309b)
    infra/monitoring/prometheus/targets/app-metrics-fly.json    — direct /metrics file_sd targets (T309b)

Idempotent: re-running with an unchanged registry rewrites identical bytes, so
`git diff` after a run is the review surface for any topology change.

Usage:
    python scripts/gen_infra.py           # write files
    python scripts/gen_infra.py --check   # exit 1 if anything is out of date

`--check` is what CI runs: it proves the committed artifacts still match the
registry, so nobody can hand-edit a Dockerfile port and quietly desync the
gateway, Prometheus, and the deploy matrix from reality.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

import yaml

REPO_ROOT = Path(__file__).resolve().parent.parent
REGISTRY = REPO_ROOT / "infra" / "services.yml"

GENERATED_BANNER = "# GENERATED by scripts/gen_infra.py from infra/services.yml — do not edit by hand."

# Pinned digests-by-tag. Bump deliberately; `--check` in CI will flag the drift
# in review rather than letting a silent base-image change ride into prod.
PYTHON_BASE = "python:3.12-slim-bookworm"
NODE_BASE = "node:22-bookworm-slim"
UV_IMAGE = "ghcr.io/astral-sh/uv:0.5.11"

PYTHON_DOCKERFILE = """\
# syntax=docker/dockerfile:1.7
{banner}
#
# {name} — {description}
# Runtime: FastAPI on uvicorn, listening on {port}.

# ── Builder: resolve and install dependencies into a self-contained venv ──────
FROM {python_base} AS builder

ENV PYTHONDONTWRITEBYTECODE=1 \\
    PYTHONUNBUFFERED=1 \\
    UV_COMPILE_BYTECODE=1 \\
    UV_LINK_MODE=copy

COPY --from={uv_image} /uv /usr/local/bin/uv

WORKDIR /src

# Dependency layer first so edits to app/ don't invalidate the resolve+download.
# uv.lock is optional (`*` glob): services that have one get a reproducible
# build; those that don't resolve at build time until a lock is committed.
COPY pyproject.toml README.md* ./
COPY uv.lock* ./
RUN uv sync --no-dev --no-install-project

# Project layer.
COPY app ./app
RUN uv sync --no-dev

# ── Runtime: slim, non-root, no build tooling ────────────────────────────────
FROM {python_base} AS runtime

ENV PYTHONDONTWRITEBYTECODE=1 \\
    PYTHONUNBUFFERED=1 \\
    PATH="/app/.venv/bin:$PATH" \\
    PORT={port}

# curl is here for the container HEALTHCHECK below; nothing else is installed.
RUN apt-get update \\
 && apt-get install -y --no-install-recommends curl \\
 && rm -rf /var/lib/apt/lists/* \\
 && groupadd --system --gid 10001 app \\
 && useradd --system --uid 10001 --gid app --no-create-home --shell /usr/sbin/nologin app

WORKDIR /app

COPY --from=builder --chown=app:app /src/.venv /app/.venv
COPY --chown=app:app app ./app

# Drop privileges: nothing in this image needs root at runtime.
USER app

EXPOSE {port}

HEALTHCHECK --interval=30s --timeout=3s --start-period=15s --retries=3 \\
  CMD curl -fsS "http://127.0.0.1:${{PORT:-{port}}}/health" || exit 1

# Honour an injected $PORT (Cloud Run assigns one and ignores EXPOSE), falling
# back to this service's registry port everywhere else. `exec` matters: it
# replaces the shell so uvicorn becomes PID 1 and receives SIGTERM directly —
# without it the shell swallows the signal and every deploy waits out the full
# termination grace period instead of draining cleanly.
CMD ["sh", "-c", "exec uvicorn app.main:app --host 0.0.0.0 --port ${{PORT:-{port}}}"]
"""

NODE_DOCKERFILE = """\
# syntax=docker/dockerfile:1.7
{banner}
#
# {name} — {description}
# Runtime: Fastify on Node 22, listening on {port}.
#
# Build context is the REPO ROOT (not {path}) because this is a pnpm workspace
# package: the lockfile and sibling packages/* it depends on live above it.
# Build with:  docker build -f {path}/Dockerfile -t {name} .

# ── Builder: install workspace deps and compile TypeScript ───────────────────
FROM {node_base} AS builder

ENV PNPM_HOME=/pnpm PATH="/pnpm:$PATH"
RUN corepack enable

WORKDIR /repo

# Manifests first so the install layer caches independently of source edits.
COPY package.json pnpm-lock.yaml pnpm-workspace.yaml tsconfig.json ./
COPY {path}/package.json {path}/
COPY packages packages

RUN pnpm install --frozen-lockfile --filter @tradequote/api-gateway...

COPY {path} {path}
RUN pnpm --filter @tradequote/api-gateway build \\
 && pnpm --filter @tradequote/api-gateway --prod deploy /out

# ── Runtime: production node_modules + compiled dist only ────────────────────
FROM {node_base} AS runtime

ENV NODE_ENV=production \\
    PORT={port}

RUN apt-get update \\
 && apt-get install -y --no-install-recommends curl \\
 && rm -rf /var/lib/apt/lists/* \\
 && groupadd --system --gid 10001 app \\
 && useradd --system --uid 10001 --gid app --no-create-home --shell /usr/sbin/nologin app

WORKDIR /app

COPY --from=builder --chown=app:app /out/node_modules ./node_modules
COPY --from=builder --chown=app:app /out/dist ./dist
COPY --from=builder --chown=app:app /out/package.json ./package.json

USER app

EXPOSE {port}

HEALTHCHECK --interval=30s --timeout=3s --start-period=15s --retries=3 \\
  CMD curl -fsS "http://127.0.0.1:${{PORT:-{port}}}/health" || exit 1

# src/config.ts already reads PORT from the environment and binds 0.0.0.0, so
# an injected $PORT (Cloud Run) is honoured with no wrapper needed.
CMD ["node", "dist/index.js"]
"""

PYTHON_DOCKERIGNORE = """\
{banner}

# Virtualenvs and caches — never ship the host's venv into the image.
.venv/
venv/
__pycache__/
*.pyc
.mypy_cache/
.pytest_cache/
.ruff_cache/
.coverage
.coverage.*
htmlcov/

# Tests and docs aren't needed in a runtime image.
tests/
README.md

# Secrets must come from the platform's secret store, never the build context.
.env
.env.*
*.pem
*.key

# Deployment metadata (would otherwise bust the build cache on every edit).
Dockerfile
.dockerignore
fly.toml
"""

NODE_DOCKERIGNORE = """\
{banner}

# The gateway builds from the repo root, so this ignore list is repo-wide.
**/node_modules/
**/.pnpm-store/
**/dist/
**/build/
**/.next/
**/.turbo/
**/coverage/
**/*.tsbuildinfo

# Other workspaces and runtimes that the gateway image doesn't need.
apps/web/
apps/mobile/
services/
infra/
docs/
tests/
scripts/

# Python + Flutter artifacts.
**/__pycache__/
**/.venv/
**/.dart_tool/

# Secrets must come from the platform's secret store, never the build context.
.env
.env.*
*.pem
*.key

# VCS and editor noise.
.git/
.github/
.vscode/
.idea/
"""

FLY_TOML = """\
{banner}
#
# {name} — {description}
# Deploy:  fly deploy --config {path}/fly.toml --app {app_name}

app = "{app_name}"
primary_region = "{region}"

[build]
  dockerfile = "Dockerfile"

[env]
  PORT = "{port}"
  APP_ENV = "production"

[http_service]
  internal_port = {port}
  # {force_https_comment}
  force_https = {force_https}
  auto_stop_machines = {auto_stop}
  auto_start_machines = true
  min_machines_running = {min_machines}
  processes = ["app"]

  [http_service.concurrency]
    type = "requests"
    soft_limit = {soft_limit}
    hard_limit = {hard_limit}

# Liveness/readiness. Fly pulls a machine out of rotation when this fails, so
# /health must stay dependency-light — it should answer even when a downstream
# is degraded, or one slow dependency will cascade into a full outage.
[[http_service.checks]]
  interval = "15s"
  timeout = "3s"
  grace_period = "20s"
  method = "GET"
  path = "/health"

[[vm]]
  size = "shared-cpu-1x"
  memory = "{memory_mb}mb"
"""


def load_registry() -> dict[str, Any]:
    with REGISTRY.open(encoding="utf-8") as fh:
        return yaml.safe_load(fh)


def render_unit(reg: dict[str, Any], unit: dict[str, Any]) -> dict[Path, str]:
    """Return {absolute path: desired content} for one deployable unit."""
    name = unit["name"]
    path = unit["path"]
    port = unit["port"]
    public = bool(unit.get("public", False))
    critical = bool(unit.get("critical", False))
    unit_dir = REPO_ROOT / path

    app_name = f"{reg['app_prefix']}-{name}"

    if unit["runtime"] == "python":
        dockerfile = PYTHON_DOCKERFILE.format(
            banner=GENERATED_BANNER,
            name=name,
            description=unit["description"],
            port=port,
            python_base=PYTHON_BASE,
            uv_image=UV_IMAGE,
        )
        dockerignore = PYTHON_DOCKERIGNORE.format(banner=GENERATED_BANNER)
    elif unit["runtime"] == "node":
        dockerfile = NODE_DOCKERFILE.format(
            banner=GENERATED_BANNER,
            name=name,
            description=unit["description"],
            port=port,
            path=path,
            node_base=NODE_BASE,
        )
        dockerignore = NODE_DOCKERIGNORE.format(banner=GENERATED_BANNER)
    else:  # pragma: no cover - registry is validated by tests/infra
        raise ValueError(f"{name}: unknown runtime {unit['runtime']!r}")

    # Private services sit behind the gateway on Fly's internal network, so
    # forcing HTTPS on them would break internal http:// service-to-service
    # calls. Only the public edge redirects.
    force_https_comment = (
        "Public edge: redirect plaintext to TLS."
        if public
        else "Internal-only: gateway reaches this over the private .internal network on http."
    )

    # Never let a money-path service cold-start on a provider webhook.
    auto_stop = "false" if (public or critical) else '"suspend"'

    fly = FLY_TOML.format(
        banner=GENERATED_BANNER,
        name=name,
        description=unit["description"],
        path=path,
        app_name=app_name,
        region=reg["primary_region"],
        port=port,
        force_https="true" if public else "false",
        force_https_comment=force_https_comment,
        auto_stop=auto_stop,
        min_machines=unit["min_machines"],
        soft_limit=200 if public else 50,
        hard_limit=250 if public else 80,
        memory_mb=unit["memory_mb"],
    )

    return {
        unit_dir / "Dockerfile": dockerfile,
        unit_dir / ".dockerignore": dockerignore,
        unit_dir / "fly.toml": fly,
    }


def render_prometheus_targets(reg: dict[str, Any]) -> dict[Path, str]:
    """Prometheus file_sd target lists, one per environment.

    Blackbox-probes every unit's /health. This needs no application code to
    work, which is why it was T309's availability signal on day one — it
    stays as the up/down check even now that T309b adds real request-level
    metrics (see `render_app_metrics_targets` below), since a unit that's
    crash-looping still needs an external prober to notice it at all.
    """
    targets_dir = REPO_ROOT / "infra" / "monitoring" / "prometheus" / "targets"

    def entries(host_for: Any) -> list[dict[str, Any]]:
        out = []
        for unit in reg["units"]:
            out.append(
                {
                    "targets": [f"{host_for(unit)}/health"],
                    "labels": {
                        "service": unit["name"],
                        "port": str(unit["port"]),
                        "runtime": unit["runtime"],
                        "tier": "edge" if unit.get("public") else "internal",
                        # Drives alert routing: critical units page, others ticket.
                        "criticality": "critical" if unit.get("critical") or unit.get("public") else "standard",
                    },
                }
            )
        return out

    # Local: the monitoring stack runs in Docker while services run on the host.
    local = entries(lambda u: f"http://host.docker.internal:{u['port']}")
    # Fly: every app is reachable on the org's private IPv6 network by app name.
    fly = entries(lambda u: f"http://{reg['app_prefix']}-{u['name']}.internal:{u['port']}")

    def dump(items: list[dict[str, Any]]) -> str:
        # JSON has no comment syntax, so provenance rides in a leading entry
        # with no targets — Prometheus ignores zero-target entries.
        doc = [{"targets": [], "labels": {"_meta": "generated by scripts/gen_infra.py"}}, *items]
        return json.dumps(doc, indent=2) + "\n"

    return {
        targets_dir / "services-local.json": dump(local),
        targets_dir / "services-fly.json": dump(fly),
    }


def render_app_metrics_targets(reg: dict[str, Any]) -> dict[Path, str]:
    """Direct Prometheus scrape targets for every unit's own `/metrics` (T309b).

    Unlike `render_prometheus_targets` above (blackbox-probing `/health`,
    which stays as the availability signal), this points Prometheus straight
    at each unit's in-process counters/histograms — real request rate, error
    rate, and per-endpoint latency, now that every unit is instrumented.

    Targets here are bare `host:port` (no path): the scrape job in
    prometheus.yml sets `metrics_path: /metrics` once for the whole job,
    rather than baking a path into every target the way the blackbox job's
    `__param_target` relabeling does.
    """
    targets_dir = REPO_ROOT / "infra" / "monitoring" / "prometheus" / "targets"

    def entries(host_for: Any) -> list[dict[str, Any]]:
        out = []
        for unit in reg["units"]:
            out.append(
                {
                    "targets": [host_for(unit)],
                    "labels": {
                        "service": unit["name"],
                        "port": str(unit["port"]),
                        "runtime": unit["runtime"],
                        "tier": "edge" if unit.get("public") else "internal",
                        "criticality": "critical" if unit.get("critical") or unit.get("public") else "standard",
                    },
                }
            )
        return out

    local = entries(lambda u: f"host.docker.internal:{u['port']}")
    fly = entries(lambda u: f"{reg['app_prefix']}-{u['name']}.internal:{u['port']}")

    def dump(items: list[dict[str, Any]]) -> str:
        doc = [{"targets": [], "labels": {"_meta": "generated by scripts/gen_infra.py"}}, *items]
        return json.dumps(doc, indent=2) + "\n"

    return {
        targets_dir / "app-metrics-local.json": dump(local),
        targets_dir / "app-metrics-fly.json": dump(fly),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify committed artifacts match the registry; write nothing",
    )
    args = parser.parse_args()

    reg = load_registry()
    desired: dict[Path, str] = {}
    for unit in reg["units"]:
        desired.update(render_unit(reg, unit))
    desired.update(render_prometheus_targets(reg))
    desired.update(render_app_metrics_targets(reg))

    stale: list[Path] = []
    for target, content in sorted(desired.items()):
        current = target.read_text(encoding="utf-8") if target.is_file() else None
        if current == content:
            continue
        stale.append(target)
        if not args.check:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content, encoding="utf-8", newline="\n")

    rel = lambda p: p.relative_to(REPO_ROOT).as_posix()  # noqa: E731

    if args.check:
        if stale:
            print("gen_infra --check: these files are out of date vs infra/services.yml:")
            for p in stale:
                print(f"  - {rel(p)}")
            print("\nRun `python scripts/gen_infra.py` and commit the result.")
            return 1
        # ASCII only in console output: this runs on Windows (cp1252) too.
        print(f"gen_infra --check: OK - {len(desired)} artifacts match the registry.")
        return 0

    if stale:
        print(f"gen_infra: wrote {len(stale)} file(s):")
        for p in stale:
            print(f"  - {rel(p)}")
    else:
        print(f"gen_infra: already up to date ({len(desired)} artifacts).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
