# Environments that must never boot on development defaults.
NON_LOCAL_ENVS = frozenset({"production", "prod", "staging", "preprod"})


class InsecureConfigurationError(RuntimeError):
    """Raised at startup when a non-local environment is running on dev defaults."""


class Settings(BaseSettings):
    model_config = SettingsConfigDict(env_prefix="", case_sensitive=False, extra="ignore")

    app_name: str = "TradeQuote Integration Service"
    app_env: str = "local"

    database_url: str = "postgresql+psycopg://tradequote:tradequote@localhost:5432/tradequote"

    # Token-at-rest encryption (T308b) — a Fernet key (32 url-safe base64
    # bytes). This default is LOCAL-DEV-ONLY, generated once and committed
    # deliberately so `docker compose up` works out of the box, exactly like
    # api-gateway's JWT_SECRET default; every non-local environment MUST
    # override it via the real env var, or every stored token becomes
    # unrecoverable garbage the moment someone forgets and it silently
    # differs between service instances.
    integration_token_encryption_key: str = DEV_ONLY_TOKEN_ENCRYPTION_KEY

    # QuickBooks Online OAuth2
    quickbooks_client_id: str = ""
    quickbooks_client_secret: str = ""
    quickbooks_redirect_uri: str = "http://localhost:8011/v1/integrations/quickbooks/callback"
    quickbooks_environment: str = "sandbox"  # sandbox | production
    quickbooks_authorize_base: str = "https://appcenter.intuit.com/connect/oauth2"
    quickbooks_oauth_base: str = "https://oauth.platform.intuit.com"
    quickbooks_api_base_sandbox: str = "https://sandbox-quickbooks.api.intuit.com"
    quickbooks_api_base_production: str = "https://quickbooks.api.intuit.com"
    quickbooks_scope: str = "com.intuit.quickbooks.accounting"

