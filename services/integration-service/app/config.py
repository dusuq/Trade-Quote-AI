"""Runtime configuration, loaded from environment (12-factor)."""

from __future__ import annotations

from pydantic_settings import BaseSettings, SettingsConfigDict


class Settings(BaseSettings):
    model_config = SettingsConfigDict(env_prefix="", case_sensitive=False, extra="ignore")

    app_name: str = "TradeQuote Integration Service"
    app_env: str = "local"

    database_url: str = "postgresql+psycopg://tradequote:tradequote@localhost:5432/tradequote"

    # Token-at-rest encryption (T308b) — a Fernet key (32 url-safe base64
    # bytes). This default is LOCAL-DEV-ONLY, generated once and committed
    # deliberately so `docker compose up` works out of the box, exactly like
    # api-gateway's JWT_SECRET default; every non-local environment MUST
    # override it via the real env var, or every stored token becomes
    # unrecoverable garbage the moment someone forgets and it silently
    # differs between service instances.
    integration_token_encryption_key: str = "wz1hLmNyzDikO1PBHvcHOl_5vsNaKlfQoR3MTexIu4o="

    # QuickBooks Online OAuth2
    quickbooks_client_id: str = ""
    quickbooks_client_secret: str = ""
    quickbooks_redirect_uri: str = "http://localhost:8011/v1/integrations/quickbooks/callback"
    quickbooks_environment: str = "sandbox"  # sandbox | production
    quickbooks_authorize_base: str = "https://appcenter.intuit.com/connect/oauth2"
    quickbooks_oauth_base: str = "https://oauth.platform.intuit.com"
    quickbooks_api_base_sandbox: str = "https://sandbox-quickbooks.api.intuit.com"
    quickbooks_api_base_production: str = "https://quickbooks.api.intuit.com"
    quickbooks_scope: str = "com.intuit.quickbooks.accounting"

    # Xero OAuth2
    xero_client_id: str = ""
    xero_client_secret: str = ""
    xero_redirect_uri: str = "http://localhost:8011/v1/integrations/xero/callback"
    xero_authorize_base: str = "https://login.xero.com/identity/connect/authorize"
    xero_oauth_base: str = "https://identity.xero.com"
    xero_api_base: str = "https://api.xero.com"
    xero_scope: str = "offline_access accounting.transactions accounting.contacts"

    # Zapier — API-key/webhook based, no OAuth. `zapier_webhook_secret` verifies
    # inbound webhook signatures; the per-tenant outbound secret generated by
    # `connect_zapier` is stored (encrypted) on the connection itself.
    zapier_webhook_secret: str = ""

    # Outbound calls to provider APIs (ADR-0003 pattern; see infrastructure/http.py)
    upstream_timeout_seconds: float = 10.0
    upstream_max_attempts: int = 3

    # Where the web UI lives — the OAuth callback redirects the browser back
    # here after completing (or failing) the provider handshake.
    web_app_url: str = "http://localhost:3000"

    default_page_size: int = 20
    max_page_size: int = 100


settings = Settings()
